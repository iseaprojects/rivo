package io.github.iseaprojects.rivo.player

import io.github.iseaprojects.rivo.data.extract.Chapter
import io.github.iseaprojects.rivo.data.extract.DeliveryKind
import io.github.iseaprojects.rivo.data.extract.HeatmapPoint
import io.github.iseaprojects.rivo.data.extract.SponsorSegment
import io.github.iseaprojects.rivo.data.extract.StreamFormat
import io.github.iseaprojects.rivo.data.extract.SubtitleTrack
import io.github.iseaprojects.rivo.data.extract.VideoDetails

/**
 * What the player should hand to Media3 for one video.
 *
 * A single [StreamFormat] is not enough: the best quality is usually a video-only DASH
 * rendition plus a separate audio track, which Media3 can only play through
 * `MergingMediaSource`. A manifest is kept as a manifest because Media3's HLS/DASH
 * sources do their own adaptive selection, including live edges.
 */
data class PlannedStream(
    val delivery: DeliveryKind,
    val videoUrl: String? = null,
    val audioUrl: String? = null,
    val manifestUrl: String? = null,
    val videoMime: String? = null,
    val audioMime: String? = null,
    val headers: Map<String, String> = emptyMap(),
    val width: Int? = null,
    val height: Int? = null,
    val label: String,
    val isLive: Boolean = false,
    /** Selection key of the audio track this plan plays, null when the only track is used. */
    val audioTrack: String? = null,
) {
    val isMerged: Boolean get() = videoUrl != null && audioUrl != null
}

/** One audio rendition offered by the track picker. */
data class AudioOption(
    /** Selection key: the track id, or the language when the backend has no ids. */
    val key: String?,
    val language: String?,
    val label: String,
    val isOriginal: Boolean,
    val bitrateKbps: Int?,
)

/** One subtitle rendition offered by the track picker. */
data class SubtitleOption(
    val language: String,
    val label: String,
    val url: String,
    val mimeType: String,
    val isAutoGenerated: Boolean,
)

/**
 * Pure format selection, kept out of the service so the rules that decide "720p muxed",
 * "1080p + audio merge" or "DASH manifest" are testable without an ExoPlayer.
 */
object StreamPlanner {

    const val MIME_HLS = "application/x-mpegURL"
    const val MIME_DASH = "application/dash+xml"
    const val MIME_VTT = "text/vtt"
    const val MIME_SRT = "application/x-subrip"
    const val MIME_TTML = "application/ttml+xml"

    /** Grouping key for backends that expose no audio track identity at all. */
    private const val SINGLE_TRACK = "single"

    /**
     * Picks the cheapest source that still gives the best quality under [maxHeight].
     *
     * Progressive muxed wins when it is as good as the video-only track, because it
     * needs no merge and no second connection. Above that, a DASH/HLS manifest is
     * preferred over hand-merging: it carries every rendition and lets Media3 adapt.
     * Hand-merging is the last resort, and it is exactly the case that used to lose
     * audio on yt-x's mpv path.
     */
    fun plan(
        details: VideoDetails,
        mode: PlayMode,
        maxHeight: Int? = null,
        audioTrack: String? = null,
    ): PlannedStream? {
        if (mode == PlayMode.AUDIO) {
            val audio = details.bestAudio(audioTrack)
            if (audio?.url != null) {
                return PlannedStream(
                    delivery = DeliveryKind.PROGRESSIVE,
                    audioUrl = audio.url,
                    audioMime = audio.mimeType,
                    headers = audio.httpHeaders,
                    label = audioLabel(audio),
                    audioTrack = audio.audioTrackKey,
                    isLive = details.isLive,
                )
            }
            val muxed = details.bestMuxed(maxHeight)
            if (muxed?.url != null) {
                return PlannedStream(
                    delivery = DeliveryKind.PROGRESSIVE,
                    videoUrl = muxed.url,
                    videoMime = muxed.mimeType,
                    headers = muxed.httpHeaders,
                    width = muxed.width,
                    height = muxed.height,
                    label = audioLabel(muxed),
                    isLive = details.isLive,
                )
            }
            return manifestPlan(details)
        }

        val muxed = details.bestMuxed(maxHeight)
        val video = details.bestVideoOnly(maxHeight)
        val audio = details.bestAudio(audioTrack)

        // A live stream needs the manifest for the sliding window even when a muxed URL
        // exists: that URL is a snapshot of the DVR window, not the live edge.
        if (details.isLive) manifestPlan(details)?.let { return it }

        // A muxed rendition at the same height is cheaper and universally supported.
        if (muxed?.url != null && (video == null || (muxed.height ?: 0) >= (video.height ?: 0))) {
            return single(muxed, details.isLive)
        }

        // A manifest carries the video-only rendition and its audio in one adaptive
        // source; it also covers the case where a stream exists only as DASH/HLS.
        if (video?.delivery == DeliveryKind.DASH || video?.delivery == DeliveryKind.HLS) {
            manifestPlan(details)?.let { return it }
        }

        if (video?.url != null) {
            val audioUrl = audio?.url
            if (audioUrl != null) {
                return PlannedStream(
                    delivery = DeliveryKind.PROGRESSIVE,
                    videoUrl = video.url,
                    audioUrl = audioUrl,
                    videoMime = video.mimeType,
                    audioMime = audio.mimeType,
                    headers = video.httpHeaders + audio.httpHeaders,
                    width = video.width,
                    height = video.height,
                    label = video.label,
                    isLive = details.isLive,
                    audioTrack = audio.audioTrackKey,
                )
            }
            return single(video, details.isLive)
        }

        if (muxed?.url != null) return single(muxed, details.isLive)
        if (audio?.url != null) {
            return PlannedStream(
                delivery = DeliveryKind.PROGRESSIVE,
                audioUrl = audio.url,
                audioMime = audio.mimeType,
                headers = audio.httpHeaders,
                label = audioLabel(audio),
                audioTrack = audio.audioTrackKey,
                isLive = details.isLive,
            )
        }
        return manifestPlan(details)
    }

    /** True when the plan has a picture, i.e. the activity should host a surface. */
    fun hasVideo(plan: PlannedStream): Boolean = plan.videoUrl != null || plan.manifestUrl != null

    /**
     * Height choices for the quality sheet, best first. A manifest has no fixed height,
     * so its own label ("auto") is the only entry.
     */
    fun qualityOptions(details: VideoDetails): List<String> = buildList {
        val heights = (details.muxed() + details.videoOnly())
            .mapNotNull { it.height }
            .distinct()
            .sortedDescending()
        heights.forEach { add("${it}p") }
        if (heights.isEmpty()) {
            val manifest = details.dashManifestUrl ?: details.hlsManifestUrl
            if (manifest != null) add("auto")
        }
    }

    /** Heights that can actually be requested without a manifest re-selection. */
    fun playableHeights(details: VideoDetails): List<Int> =
        (details.muxed() + details.videoOnly())
            .mapNotNull { it.height }
            .distinct()
            .sortedDescending()

    /**
     * The audio renditions worth offering. A single-language video still ships several
     * codecs of the *same* track, so the picker groups by track identity and stays empty
     * when there is nothing to choose: one row is a worse answer than none.
     */
    fun audioOptions(details: VideoDetails): List<AudioOption> {
        val tracks = details.audioOnly().filter { it.url != null }
        if (tracks.isEmpty()) return emptyList()
        val byTrack = tracks.groupBy { it.audioTrackKey ?: SINGLE_TRACK }
        if (byTrack.size <= 1) return emptyList()
        return byTrack.map { (key, formats) ->
            val best = formats.maxByOrNull { it.audioBitrateKbps ?: 0 } ?: formats.first()
            AudioOption(
                key = key.takeUnless { it == SINGLE_TRACK },
                language = best.audioLanguage,
                label = best.audioTrackName?.takeIf { it.isNotBlank() }
                    ?: languageName(best.audioLanguage)
                    ?: best.label,
                isOriginal = best.isOriginalAudio || best.isDefaultAudio,
                bitrateKbps = best.audioBitrateKbps,
            )
        }.sortedWith(compareByDescending<AudioOption> { it.isOriginal }.thenBy { it.label })
    }

    /** Human name for a BCP-47 tag, so a dub reads "Spanish" and not "es". */
    private fun languageName(tag: String?): String? {
        val clean = tag?.substringBefore('-')?.takeIf { it.length in 2..3 } ?: return null
        return runCatching {
            java.util.Locale.forLanguageTag(clean)
                .getDisplayLanguage(java.util.Locale.getDefault())
                .takeIf { it.isNotBlank() && !it.equals(clean, ignoreCase = true) }
        }.getOrNull()
    }

    /**
     * Side-loaded subtitles Media3 can parse. NewPipe sometimes returns `json3`, which
     * ExoPlayer cannot render; dropping those is better than a track that never shows.
     */
    fun subtitles(details: VideoDetails, preferredLanguages: List<String>): List<SubtitleOption> {
        val supported = details.subtitles.filter { it.url.isNotBlank() }
            .mapNotNull { track ->
                val mime = mimeOf(track) ?: return@mapNotNull null
                SubtitleOption(
                    language = track.languageTag,
                    label = track.label.ifBlank { track.languageTag },
                    url = track.url,
                    mimeType = mime,
                    isAutoGenerated = track.isAutoGenerated,
                )
            }
            // Manual captions win over auto-generated ones for the same language.
            .sortedBy { it.isAutoGenerated }
        val wanted = preferredLanguages.map { it.lowercase() }.filter { it.isNotBlank() }
        val filtered = if (wanted.isEmpty()) {
            supported
        } else {
            supported.filter { option ->
                wanted.any { language -> matches(option.language, language) }
            }
        }
        return filtered.distinctBy { it.language.lowercase() }
    }

    private fun single(format: StreamFormat, live: Boolean): PlannedStream? {
        val url = format.url ?: format.manifestUrl ?: return null
        return when (format.delivery) {
            DeliveryKind.HLS -> PlannedStream(
                delivery = DeliveryKind.HLS,
                manifestUrl = url,
                videoMime = MIME_HLS,
                headers = format.httpHeaders,
                label = "HLS",
                isLive = live,
            )

            DeliveryKind.DASH -> PlannedStream(
                delivery = DeliveryKind.DASH,
                manifestUrl = url,
                videoMime = MIME_DASH,
                headers = format.httpHeaders,
                label = "DASH",
                isLive = live,
            )

            else -> PlannedStream(
                delivery = DeliveryKind.PROGRESSIVE,
                videoUrl = url,
                videoMime = format.mimeType,
                headers = format.httpHeaders,
                width = format.width,
                height = format.height,
                label = format.label,
                isLive = live,
            )
        }
    }

    private fun manifestPlan(details: VideoDetails): PlannedStream? {
        details.dashManifestUrl?.takeIf { it.isNotBlank() }?.let { url ->
            return PlannedStream(
                delivery = DeliveryKind.DASH,
                manifestUrl = url,
                videoMime = MIME_DASH,
                label = "DASH",
                isLive = details.isLive,
            )
        }
        details.hlsManifestUrl?.takeIf { it.isNotBlank() }?.let { url ->
            return PlannedStream(
                delivery = DeliveryKind.HLS,
                manifestUrl = url,
                videoMime = MIME_HLS,
                label = "HLS",
                isLive = details.isLive,
            )
        }
        // Some backends only expose the manifest through a format entry.
        val manifest = (details.muxed() + details.videoOnly())
            .firstOrNull { it.delivery == DeliveryKind.HLS || it.delivery == DeliveryKind.DASH }
        return manifest?.let { single(it, details.isLive) }
    }

    private fun audioLabel(format: StreamFormat): String = when {
        format.audioBitrateKbps != null -> "${format.audioBitrateKbps} kbps"
        else -> format.label
    }

    private fun mimeOf(track: SubtitleTrack): String? = when (track.container.lowercase()) {
        "vtt", "webvtt" -> MIME_VTT
        "srt" -> MIME_SRT
        "ttml", "dfxp" -> MIME_TTML
        else -> null
    }

    private fun matches(candidate: String, wanted: String): Boolean {
        val value = candidate.lowercase()
        return value == wanted ||
            value.startsWith("$wanted-") ||
            wanted.startsWith("$value-") ||
            value.substringBefore('-') == wanted.substringBefore('-')
    }
}

/** One row of the audio picker, as it arrives through the session metadata. */
@kotlinx.serialization.Serializable
data class AudioTrackPick(
    val key: String? = null,
    val label: String,
    val detail: String? = null,
)

/** Extras carried through `MediaMetadata` so the activity can build its sheets. */
@kotlinx.serialization.Serializable
data class PlayerExtras(
    val chapters: List<Chapter> = emptyList(),
    val sponsors: List<SponsorSegment> = emptyList(),
    val heatmap: List<HeatmapPoint> = emptyList(),
    val heights: List<Int> = emptyList(),
    val audioTracks: List<AudioTrackPick> = emptyList(),
    /** Track currently playing; null means the backend's default rendition. */
    val audioTrack: String? = null,
    val qualityLabel: String? = null,
    val isAudioOnly: Boolean = false,
    val queueSize: Int = 0,
    val webUrl: String? = null,
    val extractor: String? = null,
) {
    companion object {
        const val KEY = "io.github.iseaprojects.rivo.player.EXTRAS"
    }
}
