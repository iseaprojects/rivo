/** What a stream can be used for. */
enum class StreamKind { MUXED, VIDEO_ONLY, AUDIO_ONLY }

/** How the bytes are delivered; decides which Media3 source the player builds. */
enum class DeliveryKind { PROGRESSIVE, DASH, HLS, OTHER }

/**
 * One playable rendition.
 *
 * Both backends are flattened into this shape: NewPipe's `VideoStream`/`AudioStream`
 * split and yt-dlp's `formats[]` array end up here, so the player, the downloader and
 * the quality picker only ever see one model.
 */
data class StreamFormat(
    val formatId: String,
    val kind: StreamKind,
    val delivery: DeliveryKind,
    val url: String?,
    val mimeType: String? = null,
    val container: String? = null,
    val codec: String? = null,
    val qualityLabel: String? = null,
    val height: Int? = null,
    val width: Int? = null,
    val fps: Int? = null,
    val videoBitrateKbps: Int? = null,
    val audioBitrateKbps: Int? = null,
    val totalBitrateKbps: Int? = null,
    val approxBytes: Long? = null,
    val audioLanguage: String? = null,
    /** Backend id of the audio rendition family, not of the codec. */
    val audioTrackId: String? = null,
    val audioTrackName: String? = null,
    val isOriginalAudio: Boolean = false,
    val isDefaultAudio: Boolean = false,
    val isDrm: Boolean = false,
    val itag: Int? = null,
    val manifestUrl: String? = null,
    /** Headers the CDN requires (`Referer`, `User-Agent`, `Range`-safe auth). */
    val httpHeaders: Map<String, String> = emptyMap(),
) {
    val isPlayable: Boolean get() = !isDrm && (url != null || manifestUrl != null)

    val label: String
        get() = qualityLabel
            ?: when (kind) {
                StreamKind.AUDIO_ONLY -> audioBitrateKbps?.let { "$it kbps" } ?: formatId
                else -> height?.let { "${it}p" } ?: formatId
            }

    /**
     * Identity of the audio rendition *family*: every codec and bitrate of the same dub
     * shares it, which is what a track picker has to group by. Falls back to the language
     * for backends that expose no track id.
     */
    val audioTrackKey: String?
        get() = audioTrackId?.takeIf { it.isNotBlank() }
            ?: audioLanguage?.takeIf { it.isNotBlank() }
}

