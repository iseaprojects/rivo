/**
 * Everything needed to play, download, save or preview a video.
 *
 * [summary] is the canonical identity; the format lists are kept separate instead of a
 * single "best URL" because the player needs both halves of a DASH pair to mux, and the
 * downloader needs the raw URLs to write the archive entry.
 */
data class VideoDetails(
    val summary: MediaSummary,
    val formats: List<StreamFormat> = emptyList(),
    val subtitles: List<SubtitleTrack> = emptyList(),
    val chapters: List<Chapter> = emptyList(),
    val segments: List<SponsorSegment> = emptyList(),
    val heatmap: List<HeatmapPoint> = emptyList(),
    val hlsManifestUrl: String? = null,
    val dashManifestUrl: String? = null,
    val storyboardUrl: String? = null,
    val startAtSeconds: Long = 0,
    val extractor: String = "",
    val fetchedAtEpochMs: Long = System.currentTimeMillis(),
) {
    val isLive: Boolean get() = summary.isLive
    val isUpcoming: Boolean get() = summary.isUpcoming

    fun muxed(): List<StreamFormat> = formats.filter {
        it.kind == StreamKind.MUXED && it.isPlayable && it.url != null
    }

    fun videoOnly(): List<StreamFormat> = formats.filter {
        it.kind == StreamKind.VIDEO_ONLY && it.isPlayable
    }

    fun audioOnly(): List<StreamFormat> = formats.filter {
        it.kind == StreamKind.AUDIO_ONLY && it.isPlayable
    }

    /** Best progressive/muxed rendition, capped by height when a cap is given. */
    fun bestMuxed(maxHeight: Int? = null): StreamFormat? = muxed()
        .filter { maxHeight == null || (it.height ?: 0) <= maxHeight }
        .sortedWith(compareByDescending<StreamFormat> { it.height ?: 0 }
            .thenByDescending { it.fps ?: 0 }
            .thenByDescending { it.totalBitrateKbps ?: 0 })
        .firstOrNull()

    fun bestVideoOnly(maxHeight: Int? = null): StreamFormat? = videoOnly()
        .filter { maxHeight == null || (it.height ?: 0) <= maxHeight }
        .sortedWith(compareByDescending<StreamFormat> { it.height ?: 0 }
            .thenByDescending { it.fps ?: 0 }
            .thenByDescending { it.videoBitrateKbps ?: 0 })
        .firstOrNull()

    /**
     * Best audio rendition. An explicit track wins, then the original-language track over
     * dubs, then the default track, then bitrate. The same track can exist as several
     * codecs, so matching formats are ranked by bitrate rather than by their position.
     */
    fun bestAudio(track: String? = null): StreamFormat? {
        val all = audioOnly()
        if (all.isEmpty()) return null
        val pool = track?.let { key ->
            all.filter { it.audioTrackKey == key }.ifEmpty { all }
        } ?: all
        return pool.sortedWith(compareByDescending<StreamFormat> { it.isOriginalAudio }
            .thenByDescending { it.isDefaultAudio }
            .thenByDescending { it.audioBitrateKbps ?: 0 })
            .firstOrNull()
    }

    /**
     * True when the best quality needs a separate audio track, i.e. the player has to
     * build a `MergingMediaSource` instead of a single `ProgressiveMediaSource`.
     */
    fun needsMuxing(maxHeight: Int? = null): Boolean {
        val video = bestVideoOnly(maxHeight) ?: return false
        val muxed = bestMuxed(maxHeight)
        return muxed == null || (video.height ?: 0) > (muxed.height ?: 0)
    }
}

