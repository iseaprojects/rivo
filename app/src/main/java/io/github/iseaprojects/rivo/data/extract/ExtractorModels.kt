data class ChannelTab(
    val id: String,
    val name: String,
    val url: String,
    val kind: ChannelTabKind,
)

enum class ChannelTabKind {
    VIDEOS,
    SHORTS,
    LIVE,
    PLAYLISTS,
    FEATURED,
    PODCASTS,
    RELEASES,
    OTHER,
    ;

    companion object {
        fun fromUrl(url: String): ChannelTabKind {
            val path = url.substringAfter("youtube.com", url).substringBefore('?')
            return when {
                path.endsWith("/shorts") -> SHORTS
                path.endsWith("/streams") || path.endsWith("/live") -> LIVE
                path.endsWith("/playlists") -> PLAYLISTS
                path.endsWith("/featured") -> FEATURED
                path.endsWith("/podcasts") -> PODCASTS
                path.endsWith("/releases") -> RELEASES
                path.endsWith("/videos") -> VIDEOS
                else -> OTHER
            }
        }
    }
}

/**
 * One page of a list plus the token needed to ask for the next one.
 *
 * yt-x pages explicitly (`CONFIG_PER_PAGE`) and never scrolls infinitely; the token is
 * the backend's own continuation state, encoded as opaque text so it survives process
 * death without keeping extractor objects alive.
 */
data class MediaPage(
    val items: List<MediaSummary> = emptyList(),
    val playlists: List<PlaylistSummary> = emptyList(),
    val channels: List<ChannelSummary> = emptyList(),
    val nextToken: ContinueToken? = null,
    val totalCount: Long? = null,
    val partialErrors: List<String> = emptyList(),
) {
    val isEmpty: Boolean
        get() = items.isEmpty() && playlists.isEmpty() && channels.isEmpty()
}

/** Opaque, backend-owned continuation state. */
data class ContinueToken(
    val backend: String,
    val payload: String,
)

data class ChannelResult(
    val details: ChannelDetails,
    val page: MediaPage,
)

data class PlaylistResult(
    val details: PlaylistDetails,
    val page: MediaPage,
)

/**
 * Feeds that only exist for a signed-in account, addressed by their own YouTube URL.
 *
 * These are read with the account's cookies through yt-dlp; NewPipeExtractor has no entry
 * point for them, so the fast flavor answers with a precise UNSUPPORTED instead of
 * pretending the account has no subscriptions.
 */
enum class AccountFeed(val url: String) {
    /** Videos uploaded by the channels the account follows. */
    SUBSCRIPTIONS("https://www.youtube.com/feed/subscriptions"),

    /** The channel list itself; what "Sync subscriptions" imports. */
    CHANNELS("https://www.youtube.com/feed/channels"),

    HISTORY("https://www.youtube.com/feed/history"),
    PLAYLISTS("https://www.youtube.com/feed/playlists"),

    /** Watch Later and Liked are playlists whose id is only readable with cookies. */
    WATCH_LATER("https://www.youtube.com/playlist?list=WL"),
    LIKED("https://www.youtube.com/playlist?list=LL"),
}

enum class Kiosk(val newPipeId: String? = null, val url: String? = null) {
    TRENDING("Trending", "https://www.youtube.com/feed/trending"),
    MUSIC("trending_music", "https://www.youtube.com/feed/trending?bp=4gINGgt5dG1hX2NoYXJ0cw%3D%3D"),
    GAMING("trending_gaming", "https://www.youtube.com/feed/trending?bp=4gIcGhpnYW1pbmdfY29ycHVzX21vc3RfcG9wdWxhcg%3D%3D"),
    MOVIES("trending_movies_and_shows", "https://www.youtube.com/feed/storefront?bp=ogUCKAU%3D%3D"),
    LIVE("live", "https://www.youtube.com/feed/trending?bp=4gIOGgtMaXZlX25vdyBsaXZl"),
    PODCASTS("trending_podcasts_episodes", "https://www.youtube.com/feed/trending?bp=4gIIGhZwb2RjYXN0c19lcGlzb2Rlc19saXZl"),
    ;
}

