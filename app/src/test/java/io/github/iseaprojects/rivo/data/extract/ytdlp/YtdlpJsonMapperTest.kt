package io.github.iseaprojects.rivo.data.extract.ytdlp

import io.github.iseaprojects.rivo.core.model.Availability
import io.github.iseaprojects.rivo.data.extract.ChannelTabKind
import io.github.iseaprojects.rivo.data.extract.StreamKind
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

class YtdlpJsonMapperTest {

    private val videoJson = """
        {
          "id": "abc12345678",
          "title": "Test video",
          "webpage_url": "https://www.youtube.com/watch?v=abc12345678",
          "channel": "Chan",
          "channel_id": "UC123",
          "channel_url": "https://www.youtube.com/channel/UC123",
          "description": "desc",
          "duration": 123.4,
          "view_count": 42,
          "upload_date": "20240102",
          "timestamp": 1704153600,
          "thumbnail": "https://i.ytimg.com/vi/abc12345678/hq.jpg",
          "thumbnails": [
            {"url": "https://i.ytimg.com/vi/abc12345678/hq.jpg", "width": 480, "height": 360},
            {"url": "https://i.ytimg.com/vi/abc12345678/max.jpg", "width": 1280, "height": 720}
          ],
          "availability": "public",
          "live_status": "not_live",
          "formats": [
            {"format_id": "18", "ext": "mp4", "vcodec": "avc1", "acodec": "mp4a",
             "height": 360, "width": 640, "fps": 30, "tbr": 500,
             "url": "https://cdn.example/18", "protocol": "https",
             "http_headers": {"Referer": "https://www.youtube.com/"}},
            {"format_id": "137", "ext": "mp4", "vcodec": "avc1", "acodec": "none",
             "height": 1080, "width": 1920, "fps": 30, "vbr": 4500,
             "url": "https://cdn.example/137", "protocol": "https"},
            {"format_id": "140", "ext": "m4a", "vcodec": "none", "acodec": "mp4a.40.2",
             "abr": 128, "language": "en", "language_preference": 10,
             "url": "https://cdn.example/140", "protocol": "https"},
            {"format_id": "251", "ext": "webm", "vcodec": "none", "acodec": "opus",
             "abr": 160, "language": "es", "format_note": "dubbed",
             "url": "https://cdn.example/251", "protocol": "https"}
          ],
          "subtitles": {"en": [{"ext": "vtt", "url": "https://cdn.example/sub.vtt"}]},
          "automatic_captions": {"es": [{"ext": "json3", "url": "https://cdn.example/auto.json3"}]},
          "chapters": [{"start_time": 0, "end_time": 60, "title": "Intro"}]
        }
    """.trimIndent()

    @Test
    fun `video metadata is mapped`() {
        val details = YtdlpJsonMapper.video(videoJson)

        assertEquals("abc12345678", details.summary.id)
        assertEquals("Test video", details.summary.title)
        assertEquals("Chan", details.summary.channelName)
        assertEquals("UC123", details.summary.channelId)
        assertEquals(123L, details.summary.durationSeconds)
        assertEquals(42L, details.summary.viewCount)
        assertEquals(Availability.AVAILABLE, details.summary.availability)
        // The largest thumbnail wins, not the legacy `thumbnail` scalar.
        assertEquals("https://i.ytimg.com/vi/abc12345678/max.jpg", details.summary.thumbnailUrl)
        assertEquals(1704153600000L, details.summary.publishedAtEpochMs)
    }

    @Test
    fun `format kinds and selectors`() {
        val details = YtdlpJsonMapper.video(videoJson)

        assertEquals(4, details.formats.size)
        assertEquals(1, details.formats.count { it.kind == StreamKind.MUXED })
        assertEquals(1, details.formats.count { it.kind == StreamKind.VIDEO_ONLY })
        assertEquals(2, details.formats.count { it.kind == StreamKind.AUDIO_ONLY })

        assertEquals(360, details.bestMuxed()?.height)
        assertEquals(1080, details.bestVideoOnly()?.height)

        // Original audio wins over the higher-bitrate dub.
        assertEquals("140", details.bestAudio()?.formatId)
        assertEquals("en", details.bestAudio()?.audioLanguage)
        assertTrue(details.needsMuxing())

        val muxed = details.bestMuxed()!!
        assertEquals("https://www.youtube.com/", muxed.httpHeaders["Referer"])
        assertEquals("video/mp4", muxed.mimeType)
    }

    @Test
    fun `subtitles and chapters are mapped`() {
        val details = YtdlpJsonMapper.video(videoJson)

        assertEquals(2, details.subtitles.size)
        assertTrue(details.subtitles.any { it.isAutoGenerated && it.languageTag == "es" })
        assertTrue(details.subtitles.any { !it.isAutoGenerated && it.container == "vtt" })

        assertEquals(1, details.chapters.size)
        assertEquals("Intro", details.chapters.first().title)
        assertEquals(60_000L, details.chapters.first().endMs)
    }

    @Test
    fun `a direct media file with unprobed codecs stays playable`() {
        // Verbatim shape of `yt-dlp -J https://…/file.mp4`: one format, no codecs, no
        // resolution. Dropping it used to leave the player with an empty queue.
        val details = YtdlpJsonMapper.video(
            """
            {
              "id": "mov_bbb",
              "title": "mov_bbb",
              "ext": "mp4",
              "formats": [
                {"format_id": "mp4", "url": "https://example.com/mov_bbb.mp4", "ext": "mp4",
                 "vcodec": null, "protocol": "https", "video_ext": "mp4", "audio_ext": "none",
                 "format": "mp4 - unknown",
                 "http_headers": {"User-Agent": "Mozilla/5.0"}}
              ]
            }
            """.trimIndent(),
        )

        assertEquals(1, details.formats.size)
        val format = details.formats.single()
        assertEquals(StreamKind.MUXED, format.kind)
        assertEquals("video/mp4", format.mimeType)
        assertEquals("https://example.com/mov_bbb.mp4", format.url)
        assertEquals("mp4", details.bestMuxed()?.formatId)
        assertFalse(details.needsMuxing())
    }

    @Test
    fun `a direct audio file with unprobed codecs is audio only`() {
        val details = YtdlpJsonMapper.video(
            """
            {"id": "track", "title": "Track",
             "formats": [{"format_id": "mp3", "ext": "mp3",
                          "url": "https://example.com/track.mp3", "protocol": "https"}]}
            """.trimIndent(),
        )

        assertEquals(StreamKind.AUDIO_ONLY, details.formats.single().kind)
        assertEquals("mp3", details.bestAudio()?.formatId)
    }

    @Test
    fun `upcoming and private availability`() {
        val upcoming = YtdlpJsonMapper.video(
            """{"id":"x","title":"soon","availability":"public",
                "live_status":"is_upcoming","formats":[]}""",
        )
        assertTrue(upcoming.summary.isUpcoming)

        val private = YtdlpJsonMapper.video(
            """{"id":"y","title":"hidden","availability":"private","formats":[]}""",
        )
        assertEquals(Availability.PRIVATE, private.summary.availability)
    }

    @Test
    fun `flat list splits videos playlists and channels`() {
        val page = YtdlpJsonMapper.list(
            """
            {
              "_type": "playlist",
              "title": "Mix",
              "playlist_count": 3,
              "entries": [
                {"_type": "url", "id": "aaaaaaaaaaa", "title": "A",
                 "url": "https://www.youtube.com/watch?v=aaaaaaaaaaa",
                 "duration": 10, "channel": "C"},
                {"_type": "url", "id": "PL123", "title": "P",
                 "url": "https://www.youtube.com/playlist?list=PL123", "playlist_count": 5},
                {"_type": "url", "id": "UC1", "title": "Ch",
                 "url": "https://www.youtube.com/channel/UC1"}
              ]
            }
            """.trimIndent(),
        )
        assertEquals(1, page.items.size)
        assertEquals("aaaaaaaaaaa", page.items.first().id)
        assertEquals(10L, page.items.first().durationSeconds)
        assertEquals(1, page.playlists.size)
        assertEquals(5, page.playlists.first().itemCount)
        assertEquals(1, page.channels.size)
        assertEquals(3L, page.totalCount)
    }

    @Test
    fun `channel metadata exposes the standard tabs`() {
        val result = YtdlpJsonMapper.channel(
            """
            {
              "_type": "playlist",
              "channel": "Chan",
              "channel_id": "UC1",
              "channel_url": "https://www.youtube.com/@chan",
              "channel_follower_count": 1234,
              "entries": []
            }
            """.trimIndent(),
            "https://www.youtube.com/@chan/videos",
        )
        assertEquals("Chan", result.details.summary.name)
        assertEquals(1234L, result.details.summary.subscriberCount)
        assertNotNull(result.details.tabs.firstOrNull { it.kind == ChannelTabKind.VIDEOS })
        assertNotNull(result.details.tabs.firstOrNull { it.kind == ChannelTabKind.SHORTS })
        assertTrue(result.details.tabs.size >= 5)
    }

    @Test
    fun `invalid json is reported as a broken extractor`() {
        val error = runCatching { YtdlpJsonMapper.video("not json") }.exceptionOrNull()
        assertTrue(error is io.github.iseaprojects.rivo.data.extract.ExtractorException)
    }
}
